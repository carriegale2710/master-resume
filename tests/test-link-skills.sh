#!/usr/bin/env bash
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
tmp_dir="$(mktemp -d)"
trap 'rm -rf "$tmp_dir"' EXIT

fail() {
  echo "FAIL: $1" >&2
  exit 1
}

make_fixture() {
  local root="$1"
  mkdir -p "$root/scripts" "$root/skills"
  cp "$repo_root/scripts/link-skills.sh" "$root/scripts/"
  printf 'fixture skill\n' > "$root/skills/example.md"
}

supported_root="$tmp_dir/supported"
make_fixture "$supported_root"
bash "$supported_root/scripts/link-skills.sh" claude codex gemini >/dev/null ||
  fail "supported tool names should succeed"
for tool in claude codex gemini; do
  [[ -L "$supported_root/.$tool/skills" ]] || fail "Missing .$tool/skills symlink"
  [[ "$(readlink "$supported_root/.$tool/skills")" == ../skills ]] || fail "Unexpected .$tool/skills target"
done
  bash "$supported_root/scripts/link-skills.sh" claude >/dev/null ||
    fail "re-running with the generated symlink should succeed"

  bash "$supported_root/scripts/link-skills.sh" --copy claude >/dev/null ||
    fail "--copy should replace the generated symlink"
[[ -d "$supported_root/.claude/skills" && ! -L "$supported_root/.claude/skills" ]] ||
  fail "--copy should create a directory"
[[ -f "$supported_root/.claude/skills/example.md" ]] || fail "Copied skill is missing"
grep -qx 'Generated by scripts/link-skills.sh' "$supported_root/.claude/skills/.link-skills-generated" ||
  fail "Copied skills should have an ownership marker"
bash "$supported_root/scripts/link-skills.sh" claude >/dev/null ||
  fail "link mode should replace the marked generated directory"
[[ -L "$supported_root/.claude/skills" ]] || fail "Expected generated directory to be replaced by a symlink"

unsafe_root="$tmp_dir/unsafe"
make_fixture "$unsafe_root"
for name in unknown ../outside foo/bar /tmp/outside .; do
  if bash "$unsafe_root/scripts/link-skills.sh" "$name" >/dev/null 2>&1; then
    fail "Unsafe tool name should be rejected: $name"
  fi
done
if bash "$unsafe_root/scripts/link-skills.sh" claude ../outside >/dev/null 2>&1; then
  fail "All tool names should be validated before changing paths"
fi
[[ ! -e "$unsafe_root/.claude" ]] || fail "Rejected arguments must not create tool directories"

preserve_root="$tmp_dir/preserve"
make_fixture "$preserve_root"
mkdir -p "$preserve_root/.claude/skills"
printf 'keep parent\n' > "$preserve_root/.claude/keep.txt"
printf 'keep skills\n' > "$preserve_root/.claude/skills/important.txt"
if bash "$preserve_root/scripts/link-skills.sh" claude >/dev/null 2>&1; then
  fail "Unrelated existing skills directory should not be replaced"
fi
[[ "$(cat "$preserve_root/.claude/keep.txt")" == 'keep parent' ]] ||
  fail "Unrelated tool-directory files should be preserved"
[[ "$(cat "$preserve_root/.claude/skills/important.txt")" == 'keep skills' ]] ||
  fail "Unrelated existing skills files should be preserved"

symlink_root="$tmp_dir/unrelated-symlink"
make_fixture "$symlink_root"
mkdir -p "$tmp_dir/external"
printf 'external data\n' > "$tmp_dir/external/important.txt"
mkdir "$symlink_root/.claude"
ln -s "$tmp_dir/external" "$symlink_root/.claude/skills"
if bash "$symlink_root/scripts/link-skills.sh" claude >/dev/null 2>&1; then
  fail "Unrelated existing skills symlink should not be replaced"
fi
[[ "$(readlink "$symlink_root/.claude/skills")" == "$tmp_dir/external" ]] ||
  fail "Unrelated symlink should be preserved"
[[ "$(cat "$tmp_dir/external/important.txt")" == 'external data' ]] ||
  fail "Unrelated symlink target contents should be preserved"

echo "PASS: link-skills.sh validates names and preserves unrelated paths"
