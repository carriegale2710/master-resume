#!/usr/bin/env bash
# Expose ./skills to agent tools that expect their own folder.
# Usage: bash scripts/link-skills.sh [--copy] [claude codex gemini ...]
# Default: symlink for claude, codex and gemini. --copy copies instead of linking.
set -euo pipefail
cd "$(dirname "$0")/.."

mode=link
tools=()
for a in "$@"; do
  case "$a" in
    --copy) mode=copy ;;
    claude|codex|gemini) tools+=("$a") ;;
    *)
      echo "Unsupported tool name: $a" >&2
      exit 2
      ;;
  esac
done
[ ${#tools[@]} -gt 0 ] || tools=(claude codex gemini)

marker_name=.link-skills-generated
marker_content='Generated by scripts/link-skills.sh'

for t in "${tools[@]}"; do
  d=".$t"
  if [[ -L "$d" ]]; then
    echo "Refusing to use symlinked tool directory: $d" >&2
    exit 1
  elif [[ -e "$d" ]]; then
    if [[ ! -d "$d" ]]; then
      echo "Refusing to use non-directory tool path: $d" >&2
      exit 1
    fi
  else
    mkdir "$d"
  fi

  target="$d/skills"
  if [[ -L "$target" ]]; then
    if [[ "$(readlink "$target")" != ../skills ]]; then
      echo "Refusing to replace unrelated symlink: $target" >&2
      exit 1
    fi
    rm -- "$target"
  elif [[ -e "$target" ]]; then
    marker="$target/$marker_name"
    if [[ ! -d "$target" || -L "$target" || ! -f "$marker" || -L "$marker" || "$(<"$marker")" != "$marker_content" ]]; then
      echo "Refusing to replace unrelated path: $target" >&2
      exit 1
    fi
    rm -rf -- "$target"
  fi

  if [ "$mode" = link ] && ln -s ../skills "$target" 2>/dev/null; then
    echo "Linked $d/skills -> ../skills"
  else
    cp -r skills "$target"
    printf '%s\n' "$marker_content" > "$target/$marker_name"
    echo "Copied skills to $d/skills (re-run after editing skills/)"
  fi
done
